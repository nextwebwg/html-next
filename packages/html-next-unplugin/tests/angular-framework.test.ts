it("preserves authored TypeScript side-effect imports in Angular production bundles", async () => {
  const { root } = await fixture();
  await writeFile(join(root, "src/entry.ts"), 'export { UiTyped } from "@example/controls";');
  const result = await build({ root, configFile: false, logLevel: "silent", plugins: [htmlNext({ target: "angular" })],
    build: { write: false, minify: false, lib: { entry: "src/entry.ts", formats: ["es"] }, rollupOptions: { external: [/^@angular\//] } } });
  const outputs = (Array.isArray(result) ? result : [result]).flatMap(bundle => "output" in bundle ? bundle.output : []);
  const controller = outputs.find(chunk => chunk.type === "chunk" && chunk.facadeModuleId?.endsWith("/typed.ts"));
  assert.ok(controller?.type === "chunk");
  const module = await import(`data:text/javascript;base64,${Buffer.from(controller.code).toString("base64")}`) as { connect(host: { root: { dataset: Record<string, string> } }): void };
  const host = { root: { dataset: {} as Record<string, string> } };
  try { module.connect(host); assert.equal(host.root.dataset.sideEffect, "kept"); }
  finally { Reflect.deleteProperty(globalThis, "angularSideEffect"); }
}, 60_000);
