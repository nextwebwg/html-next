import type { GeneratedArtifact } from "../generate.js";
import { MODULE_CONNECTION_SOURCE } from "../generated/module-connection-source.js";
import { CONTROLLER_STATE_SOURCE } from "./controller-state-source.js";
import { NATIVE_CONNECTION_SOURCE } from "./native-connection-source.js";
import { REQUEST_HOST_SOURCE } from "./request-host-source.js";

/** Angular supplies tracked state and effect disposal; the shared native host owns DOM connections. */
export function angularHostArtifact(version: string): GeneratedArtifact {
  return { path: "angular/host.ts", content: `// Generated by HTML Next ${version}. Do not edit.
import { Directive, ElementRef, Injector, PLATFORM_ID, computed, effect, inject, signal, untracked } from "@angular/core";
import { createInputPort, READY_INPUT, UNRESOLVED_INPUT, propValidityState, type InputStatus, type InputSnapshot } from "./state";
import { dispatchDeclared } from "./events";
${MODULE_CONNECTION_SOURCE}
${CONTROLLER_STATE_SOURCE}
${NATIVE_CONNECTION_SOURCE}
${REQUEST_HOST_SOURCE}
interface HostModel extends ControllerNamespaces {
  readonly tag: string;
  readonly definition: string;
  readonly controller?: string;
  readonly load?: () => Promise<unknown>;
  readonly module?: boolean;
  readonly props: () => Record<string, unknown>;
  readonly rawProps: () => Record<string, unknown>;
  readonly callerProps: () => Record<string, unknown>;
  readonly propContract: Parameters<typeof propValidityState>[0]["contract"];
  readonly reads: Readonly<Record<string, () => unknown>>;
  readonly availability: Readonly<Record<string, () => InputStatus>>;
  readonly publish?: (name: string, snapshot: InputSnapshot) => boolean;
  readonly refs: Readonly<Record<string, () => Element | readonly Element[] | undefined>>;
  readonly events: Readonly<Record<string, readonly [type: Parameters<typeof dispatchDeclared>[3], init: EventInit]>>;
  readonly request?: ((root: Element, signal: AbortSignal, name: string, detail?: unknown, options?: any) => Promise<unknown>)
    & { readonly has?: (host: any, own: string[]) => (name: string) => boolean };
  readonly responders?: Readonly<Record<string, () => ((event: Event) => void) | undefined>>;
  readonly scripts?: () => Readonly<Record<string, unknown>>;
  readonly connect?: () => void;
  readonly disconnect?: () => void;
}
@Directive({ selector: "[hnNextHost]", standalone: true })
export class HtmlNextHost {
  models: readonly HostModel[] = [];
  private readonly root = inject<ElementRef<Element>>(ElementRef).nativeElement;
  private readonly injector = inject(Injector);
  private readonly browser = inject(PLATFORM_ID) === "browser";
  private readonly stops: (() => void)[] = [];
  private destroyed = false;
  ngAfterViewInit(): void {
    if (!this.browser) return;
    queueMicrotask(() => { if (!this.destroyed) for (const model of this.models) this.stops.push(this.activate(model)); });
  }
  ngOnDestroy(): void { this.destroyed = true; for (const stop of this.stops) stop(); }
  private activate(options: HostModel): () => void {
    const root = this.root;
    const connected = signal(false);
    let generation = 0;
    let initialized = false;
    let loaded: Promise<{ connect?: Connect<any>; default?: (host: any) => unknown }> | undefined;
    let cleanup: (() => void) | undefined;
    const effects = new Map<() => void, () => void>();
    const subscriptions = new Set<{ type: string; listener: EventListener; stopKnown?: () => void; cleanup?: () => void; responding?: () => boolean; active?: boolean }>();
    const requests = requestConnection();
    const report = (error: unknown): void => { queueMicrotask(() => { throw error; }); };
    const event = (name: string): Event => new Event(name);
    const dispatch = (name: string, detail?: unknown): boolean => {
      const declared = options.events[name];
      if (declared === undefined) throw new TypeError("Undeclared event: " + name);
      return dispatchDeclared(root, name, detail, declared[0], declared[1]);
    };
    const validity = (name: string) => propValidityState({ contract: options.propContract, values: options.rawProps() }, name);
    const own: string[] = [];
    const host: any = {
      root, element: root,
      ...controllerNamespaces(options, options.definition),
      props: Object.freeze(Object.fromEntries(Object.keys(options.propContract.props).map(name => [name, Object.freeze({
        get value() { return options.props()[name]; }, get inputValue() { return options.rawProps()[name]; },
        get validity() { return validity(name); }, validate: () => validity(name),
      })]))),
      refs: new Proxy({}, { get: (_target, name) => typeof name === "string" ? options.refs[name]?.() : undefined,
        has: (_target, name) => typeof name === "string" && Object.hasOwn(options.refs, name) }),
      slots: new Proxy({}, { get: (_target, name) => typeof name !== "string" ? undefined : Array.from(root.querySelectorAll("[data-slotted]"))
        .filter(element => !(element.getAttribute("data-slotted") ?? "").split(" ").includes(options.tag) && element.parentElement?.closest("[data-hn]") === root && (element.getAttribute("slot") ?? "") === (name === "default" ? "" : name)) }),
      get scripts() { return options.scripts?.() ?? Object.freeze({}); },
      signal<T>(initial: T) { const value = signal(initial); return { get: value, set: value.set, update: value.update }; },
      computed<T>(evaluate: () => T) {
        let previous: T; let stopped = false;
        const value = computed(() => { if (!stopped && connected()) previous = evaluate(); return previous; });
        return { get: value, stop: () => { stopped = true; } };
      },
      effect: (run: () => void | (() => void)): (() => void) => {
        let cleanup: void | (() => void);
        const pause = (): void => { const release = cleanup; cleanup = undefined; release?.(); };
        const reaction = effect(onCleanup => { if (connected()) { cleanup = run(); onCleanup(pause); } }, { injector: this.injector, manualCleanup: true });
        const stop = (): void => { reaction.destroy(); pause(); effects.delete(stop); };
        effects.set(stop, pause); return stop;
      },
      dispatch,
      on: (type: string, callback: EventListener) => listen(type, callback),
    };
    const known = (subscription: typeof subscriptions extends Set<infer T> ? T : never): void => {
      subscription.stopKnown?.();
      subscription.active = subscription.responding?.() ?? true;
      subscription.stopKnown = subscription.active ? knownResponder(root, subscription.type, subscription.responding === undefined ? own : undefined) : undefined;
    };
    function listen(type: string, callback: EventListener, responding?: () => boolean): () => void {
        const listener = type === "connect" || type === "disconnect" ? callback : hostListener(type, callback);
        const subscription: typeof subscriptions extends Set<infer T> ? T : never = { type, listener, ...(responding === undefined ? {} : { responding }) };
        subscriptions.add(subscription);
        if (connected()) {
          if (type === "connect") {
            const result: unknown = listener(event(type)); if (typeof result === "function") subscription.cleanup = result as () => void;
          } else if (type !== "disconnect") {
            root.addEventListener(type, listener); known(subscription); relayResponders(root, type);
          }
        }
        return () => { subscriptions.delete(subscription); root.removeEventListener(type, listener); subscription.stopKnown?.(); subscription.cleanup?.(); };
    }
    if (options.request !== undefined) host.request = (name: string, detail?: unknown, config?: unknown) => options.request!(root, requests.signal(connected()), name, detail, config);
    if (options.request?.has !== undefined) host.hasResponder = options.request.has(host, own);
    for (const [name, read] of Object.entries(options.responders ?? {})) listen(name, event => read()?.(event), () => read() !== undefined);
    if (Object.keys(options.responders ?? {}).length > 0) host.effect(() => {
      for (const subscription of subscriptions) if (subscription.responding !== undefined && subscription.responding() !== subscription.active) {
        known(subscription); if (subscription.active) relayResponders(root, subscription.type);
      }
    });
    const inputs = createInputPort({ names: Object.keys(options.propContract.props), readNames: Object.keys(options.reads),
      read: name => options.reads[name]?.(), status: name => options.availability[name]?.() ?? READY_INPUT,
      supplied: name => options.callerProps()[name] !== undefined,
      publish: (name, snapshot) => options.publish?.(name, snapshot) ?? false,
      untracked, watch: run => host.effect(run),
    });
    Object.defineProperty(host, Symbol.for("@nextwebwg/html-next.inputs.v1"), { value: inputs });
    Object.freeze(host);
    const disconnect = (): void => {
      if (!connected()) return;
      connected.set(false); generation++; requests.end();
      options.disconnect?.();
      for (const subscription of subscriptions) {
        if (subscription.type === "disconnect") subscription.listener(event("disconnect"));
        else if (subscription.type !== "connect") root.removeEventListener(subscription.type, subscription.listener);
        subscription.stopKnown?.(); subscription.cleanup?.(); subscription.cleanup = undefined;
      }
      for (const pause of effects.values()) pause();
      const release = cleanup; cleanup = undefined; release?.();
    };
    const synchronize = (): void => {
      if (!root.isConnected) { disconnect(); return; }
      if (connected()) return;
      connected.set(true); const current = ++generation;
      options.connect?.();
      for (const subscription of subscriptions) {
        if (subscription.type === "connect") {
          const result: unknown = subscription.listener(event("connect")); if (typeof result === "function") subscription.cleanup = result as () => void;
        } else if (subscription.type !== "disconnect") {
          root.addEventListener(subscription.type, subscription.listener); known(subscription); relayResponders(root, subscription.type);
        }
      }
      if (options.load === undefined || initialized && !options.module) return;
      const release = holdController(root);
      loaded ??= options.load().then(value => {
        const module = value as { connect?: Connect<any>; default?: (host: any) => unknown };
        if (module === null || typeof module !== "object" || (options.module ? module.connect !== undefined && typeof module.connect !== "function" : typeof module.default !== "function")) throw new Error("HJ002: Invalid controller module " + options.controller);
        return module;
      }).catch(error => { if (error instanceof Error && error.message.startsWith("HJ002:")) throw error; throw new Error("HJ001: Could not load " + options.controller + ": " + (error instanceof Error ? error.message : String(error)), { cause: error }); });
      void loaded.then(async module => {
        if (!connected() || current !== generation) return;
        initialized = true;
        if (options.module) cleanup = activateModule(module, host, report);
        else {
          const result = await module.default!(host);
          if (typeof result === "function") { if (!connected() || current !== generation) (result as () => void)(); else cleanup = result as () => void; }
        }
      }).catch(report).finally(release);
    };
    const stop = observeConnection(root, () => untracked(synchronize));
    untracked(synchronize);
    return () => { stop(); disconnect(); for (const release of [...effects.keys()]) release(); subscriptions.clear(); };
  }
}
` };
}
