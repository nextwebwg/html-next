import type { GeneratedArtifact } from "../generate.js";

/** Angular owns the branch views and their disposal; the controller outlives a native root choice. */
export function angularNativeViewArtifact(version: string): GeneratedArtifact {
  return { path: "angular/view.ts", content: `// Generated by HTML Next ${version}. Do not edit.
import { ApplicationRef, Directive, ElementRef, EnvironmentInjector, EventEmitter, InjectionToken, Injector, PLATFORM_ID, PendingTasks, Renderer2, TemplateRef, TransferState, ViewContainerRef, createComponent, inject, input, makeStateKey, reflectComponentType, type ComponentRef, type EmbeddedViewRef, type Type } from "@angular/core";
import { attachNativeEvents, type NativeBinding } from "./events";
export type { NativeBinding } from "./events";
interface NativeView { hnController: any; hnView(): TemplateRef<unknown>; }
const VIEW_COUNTS = new InjectionToken<Map<string, number>>("html-next.native-view-counts", { providedIn: "root", factory: () => new Map() });
// Serialize inert template views before visible roots. Angular 21's annotation pass
// otherwise inserts empty-text markers again after each additional application view.
const ORDER_SSR_VIEWS = new InjectionToken<() => void>("html-next.ssr-view-order", { providedIn: "root", factory: () => {
  const application = inject(ApplicationRef), tasks = inject(PendingTasks); let queued = false;
  return () => {
    if (queued) return; queued = true;
    void tasks.run(async () => {
      await Promise.resolve(); queued = false;
      for (const component of application.components) {
        const element = component.location.nativeElement as Element, parent = element.parentNode, next = element.nextSibling;
        application.detachView(component.hostView); application.attachView(component.hostView);
        parent?.insertBefore(element, next);
      }
    });
  };
} });
@Directive({ selector: "[hnNextView]", standalone: true })
export class HtmlNextView {
  private readonly container = inject(ViewContainerRef);
  readonly content = inject<TemplateRef<unknown>>(TemplateRef);
  private readonly environmentInjector = inject(EnvironmentInjector);
  private readonly injector = inject(Injector);
  private readonly renderer = inject(Renderer2);
  private readonly application = inject(ApplicationRef);
  private readonly transfer = inject(TransferState);
  private readonly browser = inject(PLATFORM_ID) === "browser";
  private readonly counts = inject(VIEW_COUNTS);
  private readonly orderServerViews = inject(ORDER_SSR_VIEWS);
  holder: ComponentRef<NativeView> | undefined;
  private root: Element | undefined;
  private readonly outputs = new Map<string, EventEmitter<Event>>();
  private readonly listeners = new Map<string, (event: Event) => void>();
  private attributes: Record<string, unknown> = {};
  private bindings: readonly NativeBinding[] = [];
  private stopEvents: (() => void) | undefined;
  private eventKey = "";
  mount(controller: unknown, component: Type<NativeView>): void {
    const selector = reflectComponentType(component)!.selector;
    const anchor = this.container.element.nativeElement as Comment;
    let identity: string | undefined;
    if (this.browser) {
      const match = /\\|html-next-view:([a-z0-9-]+:[0-9]+)$/.exec(anchor.nodeValue ?? "");
      identity = match?.[1];
      if (match) this.renderer.setValue(anchor, anchor.nodeValue!.slice(0, match.index));
    } else {
      const index = this.counts.get(selector) ?? 0; this.counts.set(selector, index + 1);
      identity = selector + ":" + index;
    }
    // Async server producers can create views in a different order from client adoption.
    // The existing template anchor carries its own identity across the native HTML parser.
    const key = makeStateKey<string>("html-next.native-view:" + identity);
    const saved = this.browser && identity !== undefined ? this.transfer.get(key, "") : "";
    let hostElement: Element | undefined;
    if (saved) {
      const template = this.renderer.createElement("template") as HTMLTemplateElement;
      this.renderer.setProperty(template, "innerHTML", saved);
      hostElement = template.content.firstElementChild ?? undefined; this.transfer.remove(key);
    }
    this.holder = createComponent(component, { environmentInjector: this.environmentInjector, elementInjector: this.injector, ...(hostElement ? { hostElement } : {}) });
    this.holder.instance.hnController = controller;
    this.application.attachView(this.holder.hostView);
    if (!this.browser) this.orderServerViews();
    if (!this.browser) this.transfer.onSerialize(key, () => {
      this.renderer.setValue(anchor, (anchor.nodeValue ?? "").replace(/\\|html-next-view:[a-z0-9-]+:[0-9]+$/, "") + "|html-next-view:" + identity);
      return this.holder!.location.nativeElement.outerHTML as string;
    });
    this.holder.changeDetectorRef.detectChanges();
    this.container.createEmbeddedView(this.holder.instance.hnView(), {});
  }
  output<T extends Event = Event>(name: string): EventEmitter<T> {
    let output = this.outputs.get(name);
    if (output === undefined) {
      output = new EventEmitter<Event>(); this.outputs.set(name, output);
      const listener = (event: Event) => output!.emit(event);
      this.listeners.set(name, listener); this.root?.addEventListener(name, listener);
    }
    return output as unknown as EventEmitter<T>;
  }
  attach(root: Element): () => void {
    if (this.root) for (const [name, listener] of this.listeners) this.root.removeEventListener(name, listener);
    this.root = root; this.attributes = {}; this.eventKey = "";
    for (const [name, listener] of this.listeners) root.addEventListener(name, listener);
    return () => { for (const [name, listener] of this.listeners) root.removeEventListener(name, listener); if (this.root === root) { this.root = undefined; this.stopEvents?.(); this.stopEvents = undefined; } };
  }
  forward(values: Record<string, unknown>, authored: readonly string[]): void {
    const root = this.root;
    if (!root) return;
    const next = Object.fromEntries(Object.entries(values).filter(([name, value]) => value !== undefined && (!authored.includes(name) || name === "class" || name === "style")));
    for (const [name, value] of Object.entries({ ...this.attributes, ...next })) {
      if (name === "class") {
        const old = String(this.attributes[name] ?? "").split(/\\s+/).filter(Boolean);
        const current = String(next[name] ?? "").split(/\\s+/).filter(Boolean);
        for (const token of old) if (!current.includes(token) && !authored.includes("class." + token)) this.renderer.removeClass(root, token);
        for (const token of current) if (!authored.includes("class." + token)) this.renderer.addClass(root, token);
      } else if (name === "style") {
        const parse = (value: unknown): Record<string, unknown> => {
          if (value !== null && typeof value === "object") return value as Record<string, unknown>;
          const probe = this.renderer.createElement("span") as HTMLElement;
          probe.style.cssText = value == null ? "" : String(value);
          return Object.fromEntries(Array.from(probe.style).map(name => [name, probe.style.getPropertyValue(name)]));
        };
        const previous = parse(this.attributes.style), current = parse(next.style);
        for (const key of new Set([...Object.keys(previous), ...Object.keys(current)])) {
          if (authored.includes("style." + key)) continue;
          if (current[key] == null) this.renderer.removeStyle(root, key, 2);
          else this.renderer.setStyle(root, key, current[key], 2);
        }
      } else if (name.startsWith("class.")) {
        if (next[name]) this.renderer.addClass(root, name.slice(6)); else this.renderer.removeClass(root, name.slice(6));
      } else if (name.startsWith("style.")) {
        if (next[name] == null) this.renderer.removeStyle(root, name.slice(6), 2); else this.renderer.setStyle(root, name.slice(6), next[name], 2);
      } else if (name.startsWith(".")) this.renderer.setProperty(root, name.slice(1), next[name]);
      else {
        const textBoolean = name.startsWith("aria-") || ["contenteditable", "draggable", "spellcheck"].includes(name);
        if (!(name in next) || value == null || value === false && !textBoolean) this.renderer.removeAttribute(root, name);
        else this.renderer.setAttribute(root, name, value === true && !textBoolean ? "" : String(value));
      }
    }
    this.attributes = next;
  }
  forwardEvents(bindings: readonly NativeBinding[]): void {
    this.bindings = bindings;
    const key = JSON.stringify(bindings.map(binding => [binding.type, binding.modifiers]));
    if (!this.root || key === this.eventKey) return;
    this.stopEvents?.(); this.eventKey = key;
    this.stopEvents = attachNativeEvents(this.root, bindings.map((binding, index) => ({ ...binding, handler: event => this.bindings[index]!.handler(event) })));
  }
  ngOnDestroy(): void { if (this.holder) { this.application.detachView(this.holder.hostView); this.holder.destroy(); } }
}
/** The consumer template is created at its actual slot, so Angular hydrates its bindings in place. */
@Directive({ selector: "[hnNextSlot]", standalone: true })
export class HtmlNextSlot {
  readonly template = input<TemplateRef<any> | undefined>(undefined, { alias: "hnNextSlot" });
  readonly fallback = input<TemplateRef<any> | undefined>(undefined, { alias: "hnNextSlotFallback" });
  readonly name = input("", { alias: "hnNextSlotName" });
  private readonly container = inject(ViewContainerRef);
  private supplied: EmbeddedViewRef<unknown> | undefined;
  private empty: EmbeddedViewRef<unknown> | undefined;
  private selected: TemplateRef<any> | undefined;
  ngDoCheck(): void {
    const template = this.template();
    if (template !== this.selected) {
      this.container.clear(); this.supplied = undefined; this.empty = undefined; this.selected = template;
      if (template) this.supplied = this.container.createEmbeddedView(template, {});
    }
    // An absent slot still owns an empty anchor; fallback views share that container.
    if (!template && !this.empty && this.fallback()) this.empty = this.container.createEmbeddedView(this.fallback()!, {});
  }
  ngAfterViewChecked(): void {
    const nodes = this.supplied?.rootNodes as Node[] | undefined;
    const content = nodes?.some(node => node.nodeType === 1 || node.nodeType === 3 && !!node.textContent?.trim());
    for (const node of nodes ?? []) if (node.nodeType === 1) {
      if (!(node as Element).hasAttribute("data-slotted")) (node as Element).setAttribute("data-slotted", "");
      if (this.name()) (node as Element).setAttribute("slot", this.name());
    }
    if (!content && !this.empty && this.fallback()) {
      this.empty = this.container.createEmbeddedView(this.fallback()!, {}); this.empty.detectChanges();
    } else if (content && this.empty) {
      this.container.remove(this.container.indexOf(this.empty)); this.empty = undefined;
    }
  }
}

` };
}

interface NativeViewSource {
  readonly tag: string;
  readonly component: string;
  readonly name: string;
  readonly declaration: string;
  readonly arguments: string;
  readonly template: string;
  readonly host: Readonly<Record<string, string>>;
  readonly fields: readonly string[];
  readonly methods: readonly string[];
  readonly slotQueries: readonly string[];
  readonly dependencies: readonly string[];
  readonly providers: readonly string[];
  readonly styles: string;
  readonly injections: readonly { name: string; type: string }[];
  readonly initialize: string;
  readonly events: readonly { name: string; type: string }[];
  readonly props: readonly string[];
  readonly viewSpecifier: string;
}

/** A template anchor owns state while Angular creates the authored native branches. */
export function angularNativeViewSource(source: NativeViewSource): string {
  const quote = JSON.stringify;
  const type = source.name + source.arguments;
  const rootName = source.name + "NativeRoot";
  const holderName = source.name + "NativeView";
  const alias = "hn" + source.name + "Root";
  const preamble = source.component.slice(0, source.component.lastIndexOf("\n@Component({"));
  const ownerExpression = (value: string): string => value.replace(/\b(hn\w*)(?=\()/g, "hnOwner().$1");
  const template = source.template;
  const queries = source.fields.filter(field => / = viewChildren</.test(field));
  const fields = source.fields.map(field => / = viewChildren</.test(field)
    ? field.replace(/ = viewChildren<.*$/, ` = () => (this.hnView.holder?.instance as ${holderName} | undefined)?.${field.match(/readonly (\w+)/)![1]}() ?? [];`) : field);
  const attributes = ["id", "class", "style", "title", "role", "tabindex", "hidden", "inert", "slot", "lang", "dir", "accesskey"].filter(name => !source.props.includes(name));
  return `${preamble}
import { viewChild, EventEmitter, Output } from "@angular/core";
import { HtmlNextView, HtmlNextSlot, type NativeBinding } from ${quote(source.viewSpecifier)};
export { HtmlNextView as ɵHtmlNextView } from ${quote(source.viewSpecifier)};
@Directive({ selector: ${quote(`[${alias}]`)}, standalone: true,
  ${source.injections.length === 0 ? "" : `hostDirectives: [${source.injections.map(item => item.type).join(", ")}],`}
  host: ${quote(Object.fromEntries(Object.entries(source.host).map(([key, value]) => [key, key.startsWith("[") || key.startsWith("(") ? ownerExpression(value) : value])))} })
class ${rootName} {
  readonly hnOwner = input.required<${type}>({ alias: ${quote(alias)} });
  readonly hnAuthored = input<readonly string[]>([], { alias: ${quote(alias + "Authored")} });
  private readonly element = inject<ElementRef<HTMLElement>>(ElementRef);
  ${source.injections.map(item => `readonly ${item.name} = inject(${item.type});`).join("\n  ")}
  private stop: (() => void) | undefined;
  ngOnInit(): void { const owner = this.hnOwner(); owner.hnRoot = this.element; ${source.injections.map(item => `owner.${item.name} = this.${item.name};`).join(" ")} owner.hnInitializeRoot(); this.stop = owner.hnView.attach(this.element.nativeElement); }
  ngAfterViewChecked(): void { const owner = this.hnOwner(); owner.hnView.forward(owner.hnForwardedAttributes(), this.hnAuthored()); owner.hnView.forwardEvents(owner.hnCallerEvents()); }
  ngOnDestroy(): void { this.stop?.(); }
}
@Directive({ selector: ${quote(`ng-template[${source.tag}]`)}, standalone: true,
  hostDirectives: [HtmlNextView], ${source.providers.length === 0 ? "" : `providers: [${source.providers.join(", ")}],`} })
export default class ${source.name}${source.declaration} {
  hnRoot = inject<ElementRef<HTMLElement>>(ElementRef);
  readonly hnView = inject(HtmlNextView);
  ${source.injections.map(item => `${item.name}!: ${item.type};`).join("\n  ")}
  readonly hnSlotTemplates = input<Record<string, TemplateRef<any> | undefined>>({}, { alias: "slots" });
  readonly hnAttributes = input<Record<string, unknown>>({});
  readonly hnCallerEvents = input<readonly NativeBinding[]>([], { alias: "hnEvents" });
  ${attributes.map((name, index) => `readonly hnAttribute${index} = input<unknown>(undefined, { alias: ${quote(name)} });`).join("\n  ")}
  hnForwardedAttributes(): Record<string, unknown> { return { ${attributes.map((name, index) => `${quote(name)}: this.hnAttribute${index}(),`).join(" ")} ...this.hnAttributes() }; }
  ${source.events.map((event, index) => `@Output(${quote(event.name)}) get hnOutput${index}(): EventEmitter<${event.type}> { return this.hnView.output<${event.type}>(${quote(event.name)}); }`).join("\n  ")}
  ${source.slotQueries.join("\n  ")}
  ${fields.join("\n  ")}
  ${source.methods.join("\n  ")}
  hnInitializeRoot(): void { ${source.initialize} }
  ngOnInit(): void { this.hnView.mount(this, ${holderName}); }
}
@Component({ selector: ${quote(source.name.toLowerCase() + "-native-view")}, standalone: true,
  imports: [${[rootName, "HtmlNextSlot", ...source.dependencies.map(name => `forwardRef(() => ${name})`)].join(", ")}],
  changeDetection: ChangeDetectionStrategy.OnPush, encapsulation: ViewEncapsulation.None,
  template: ${quote(`<ng-template #hnView>${template}</ng-template>`)}, styles: [${quote(source.styles)}] })
class ${holderName} {
  hnController!: ${type};
  readonly hnView = viewChild.required<TemplateRef<unknown>>("hnView");
  ${queries.join("\n  ")}
}
`;
}
