import type { GeneratedArtifact } from "../generate.js";

/** Native constraints can erase opaque drafts even when a hydration write repeats their value. */
export function angularControlsRendererArtifact(version: string): GeneratedArtifact {
  return { path: "angular/native-controls.ts", content: `// Generated by HTML Next ${version}. Do not edit.
import { NgModule, RendererFactory2, inject, provideEnvironmentInitializer, type Renderer2 } from "@angular/core";
const factories = new WeakSet<RendererFactory2>(), renderers = new WeakSet<Renderer2>();
@NgModule({ providers: [provideEnvironmentInitializer(() => {
  const factory = inject(RendererFactory2);
  if (factories.has(factory)) return;
  factories.add(factory);
  const create = factory.createRenderer;
  factory.createRenderer = function(host, type) {
    const renderer = create.call(this, host, type);
    if (!renderers.has(renderer)) {
      renderers.add(renderer);
      const setAttribute = renderer.setAttribute;
      renderer.setAttribute = function(element, name, value, namespace) {
        if (!namespace && element?.localName === "input" && ["min", "max", "step"].includes(name) && element.getAttribute(name) === value) return;
        setAttribute.call(this, element, name, value, namespace);
      };
    }
    return renderer;
  };
})] })
export class HtmlNextNativeControls {}
` };
}
