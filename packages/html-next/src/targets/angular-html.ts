import type { GeneratedArtifact } from "../generate.js";
import { SAFE_HTML_SANITIZER_SOURCE } from "./shared-generated.js";
import { SAFE_DEFAULT_ELEMENTS } from "../sanitizer-default.js";
import { isVoidElement } from "./shared.js";

/** Angular owns each sanitized node as a view, including SSR hydration and disposal. */
export function angularHtmlFragmentTemplate(): string {
  const children = '<ng-container [ngTemplateOutlet]="hnHtmlNodes" [ngTemplateOutletContext]="{ $implicit: hnNode.children }"></ng-container>';
  const branches = Object.entries(SAFE_DEFAULT_ELEMENTS).flatMap(([namespace, tags]) => Object.keys(tags).map(name => {
    const tag = namespace === "html" ? name : `${namespace === "mathml" ? "math" : namespace}:${name}`;
    const element = `<${tag} [hnNextHtmlAttributes]="hnNode.attributes">${namespace === "html" && isVoidElement(name) ? "" : `${children}</${tag}>`}`;
    return `@case (${JSON.stringify(`${namespace}:${name}`)}) {${element}}`;
  })).join("");
  return `<ng-template #hnHtmlNodes let-hnNodes>@for (hnNode of hnNodes; track hnNode) {@if (hnNode.text !== undefined) {{{ hnNode.text }}} @else {@switch (hnNode.tag) {${branches}}}}</ng-template>`;
}

export function angularHtmlArtifact(version: string): GeneratedArtifact {
  return { path: "angular/html.ts", content: `// Generated by HTML Next ${version}. Do not edit.
import { Directive, ElementRef, Input, Renderer2, TemplateRef, ViewContainerRef, inject, type EmbeddedViewRef } from "@angular/core";
import { defaultTreeAdapter, html as parse5Html, parseFragment, serialize, type DefaultTreeAdapterTypes } from "parse5";
${SAFE_HTML_SANITIZER_SOURCE}
interface HtmlBinding { readonly value: unknown; readonly owner: string; readonly fallback?: string; }
interface HtmlNode { readonly text?: string; readonly tag?: string; readonly attributes?: Readonly<Record<string, string>>; readonly children?: readonly HtmlNode[]; }
@Directive({ selector: "[hnNextHtmlAttributes]", standalone: true })
export class HtmlNextHtmlAttributes {
  private readonly element = inject<ElementRef<Element>>(ElementRef).nativeElement;
  private readonly renderer = inject(Renderer2);
  private previous: Readonly<Record<string, string>> = {};
  @Input() set hnNextHtmlAttributes(attributes: Readonly<Record<string, string>>) {
    for (const name of Object.keys(this.previous)) if (!(name in attributes)) this.renderer.removeAttribute(this.element, name);
    for (const [name, value] of Object.entries(attributes)) if (this.element.getAttribute(name) !== value) this.renderer.setAttribute(this.element, name, value);
    this.previous = attributes;
  }
}
@Directive({ selector: "[hnNextHtmlFragment]", standalone: true })
export class HtmlNextHtmlFragment {
  private readonly template = inject<TemplateRef<{ $implicit: readonly HtmlNode[] }>>(TemplateRef);
  private readonly container = inject(ViewContainerRef);
  private view: EmbeddedViewRef<{ $implicit: readonly HtmlNode[] }> | undefined;
  private previous: string | undefined;
  private owner: string | undefined;
  private sanitized: string | undefined;
  @Input() set hnNextHtmlFragment(binding: HtmlBinding) {
    let value = binding.value;
    if (value !== null && typeof value === "object" && "kind" in value && value.kind === "trusted-html" && "value" in value) value = value.value;
    if (value != null && typeof value !== "string") return;
    if (value == null) { if (this.previous !== undefined) return; value = binding.fallback ?? ""; }
    if (value === this.previous && binding.owner === this.owner) return;
    const sameOwner = this.owner === binding.owner;
    this.previous = value as string; this.owner = binding.owner;
    const context = defaultTreeAdapter.createElement("template", HTML_NAMESPACE, []);
    const fragment = parseFragment(context, value as string, {});
    sanitizeServer(fragment);
    const sanitized = serialize(fragment);
    if (sanitized === this.sanitized && sameOwner) return;
    this.sanitized = sanitized;
    const nodes = (children: readonly DefaultTreeAdapterTypes.ChildNode[]): HtmlNode[] => children.flatMap<HtmlNode>(node => {
      if ("tagName" in node) return [{ tag: NAMESPACES[node.namespaceURI] + ":" + node.tagName,
        attributes: { ...Object.fromEntries(node.attrs.map(attribute => [attribute.name, attribute.value])), "data-hn-owner": binding.owner }, children: nodes(node.childNodes) }];
      return node.nodeName === "#text" && "value" in node ? [{ text: node.value }] : [];
    });
    const content = nodes(fragment.childNodes);
    if (this.view) this.view.context.$implicit = content;
    else this.view = this.container.createEmbeddedView(this.template, { $implicit: content });
  }
}
/** This region has no Angular child views. Renderer2 owns only its sanitized content. */
@Directive({ selector: "[hnNextHtml]", standalone: true })
export class HtmlNextHtml {
  @Input("hnNextHtml") binding: HtmlBinding | undefined;
  private readonly root = inject<ElementRef<Element>>(ElementRef).nativeElement;
  private readonly renderer = inject(Renderer2);
  private previous: string | undefined;
  private raw: unknown;
  private owner: string | undefined;
  ngAfterViewChecked(): void {
    const binding = this.binding;
    if (binding === undefined) return;
    let value = binding.value;
    if (value !== null && typeof value === "object" && "kind" in value && value.kind === "trusted-html" && "value" in value) value = value.value;
    if (value != null && typeof value !== "string") return;
    if (value == null) { if (this.previous !== undefined) return; value = binding.fallback ?? ""; }
    if (value === this.raw && binding.owner === this.owner) return;
    this.raw = value; this.owner = binding.owner;
    const context = defaultTreeAdapter.createElement("template", HTML_NAMESPACE, []);
    const fragment = parseFragment(context, value as string, {});
    sanitizeServer(fragment);
    const own = (nodes: readonly DefaultTreeAdapterTypes.ChildNode[]): void => {
      for (const node of nodes) if ("tagName" in node) {
        node.attrs = node.attrs.filter(attribute => attribute.name !== "data-hn-owner");
        node.attrs.push({ name: "data-hn-owner", value: binding.owner }); own(node.childNodes);
      }
    };
    own(fragment.childNodes);
    const html = serialize(fragment);
    if (html === this.previous) return;
    this.previous = html;
    // A matching server-rendered region retains its nodes and native DOM state during hydration.
    if (this.root.innerHTML === html) return;
    for (const child of Array.from(this.root.childNodes)) this.renderer.removeChild(this.root, child);
    const append = (parent: Node, nodes: readonly DefaultTreeAdapterTypes.ChildNode[]): void => {
      for (const node of nodes) {
        if (node.nodeName === "#text" && "value" in node) this.renderer.appendChild(parent, this.renderer.createText(node.value));
        else if ("tagName" in node) {
          const element: Element = this.renderer.createElement(node.tagName, node.namespaceURI === HTML_NAMESPACE ? undefined : node.namespaceURI);
          for (const attribute of node.attrs) this.renderer.setAttribute(element, attribute.name, attribute.value, attribute.prefix);
          append(element, node.childNodes); this.renderer.appendChild(parent, element);
        }
      }
    };
    append(this.root, fragment.childNodes);
  }
}
` };
}
