import { CLASS_TEXT_SOURCE } from "./class-text.js";
import { inlineStyleArtifacts } from "./inline-style.js";
import type { GeneratedArtifact } from "../generate.js";

const SOURCE = `export interface Decoration {
  readonly kind: 'class' | 'style' | 'attribute';
  readonly name: string;
  readonly read: () => unknown;
}

${CLASS_TEXT_SOURCE.replace("function classText", "export function classText")}
`;

export function svelteDecorationsArtifact(version: string): GeneratedArtifact {
  return Object.freeze({ path: "svelte/decorations.ts", content: `// Generated by HTML Next ${version}. Do not edit.\n${SOURCE}` });
}


export function svelteStyleArtifacts(version: string): readonly GeneratedArtifact[] {
  return inlineStyleArtifacts("svelte", version);
}
