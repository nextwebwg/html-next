import type { GeneratedArtifact } from "../generate.js";
import { DATA_URL_SOURCE } from "./shared-generated.js";
import { NATIVE_CONNECTION_SOURCE } from "./native-connection-source.js";

export function angularDataArtifact(version: string): GeneratedArtifact {
  return { path: "angular/data.ts", content: `// Generated by HTML Next ${version}. Do not edit.
import { DestroyRef, afterNextRender, computed, effect, inject, signal, untracked, type Signal } from "@angular/core";
${DATA_URL_SOURCE}
${NATIVE_CONNECTION_SOURCE}
interface DataOptions {
  readonly source?: string;
  readonly definition: string;
  readonly type?: string;
  readonly debounce?: number;
  readonly poll?: number;
  readonly sources: () => readonly unknown[];
  readonly parameters: () => Record<string, unknown>;
}
export interface DataState { readonly pending: boolean; readonly value: any; readonly error: unknown; readonly ok: boolean; }
/** Native fetch and cancellation; Angular owns reactive dependencies and cleanup. Reads start only in a browser connection. */
export function createDataRead(root: Element, options: DataOptions): Signal<DataState> {
  const state = signal<DataState>({ pending: true, value: null, error: null, ok: false });
  const connected = signal(false);
  const key = computed(() => dataKey(options.sources()));
  let stop: (() => void) | undefined;
  afterNextRender(() => {
    const synchronize = () => connected.set(root.isConnected);
    stop = observeConnection(root, synchronize); synchronize();
  });
  inject(DestroyRef).onDestroy(() => stop?.());
  effect(onCleanup => {
    if (!connected() || options.source === undefined) return;
    key();
    const parameters = untracked(options.parameters);
    const definition = new URL(options.definition || root.ownerDocument.baseURI, root.ownerDocument.baseURI).href;
    const url = dataURL(options.source, definition, parameters);
    const controller = new AbortController();
    let timer: ReturnType<typeof setTimeout> | undefined;
    let previous = untracked(state).value;
    const request = async (): Promise<void> => {
      if (controller.signal.aborted) return;
      state.set({ pending: true, value: previous, error: null, ok: false });
      try {
        const response = await fetch(url, { signal: controller.signal });
        if (!response.ok) throw new TypeError("Request failed with " + response.status + ".");
        const value = options.type === "string" || options.type === "text" ? await response.text() : await response.json();
        if (controller.signal.aborted) return;
        previous = value; state.set({ pending: false, value, error: null, ok: true });
      } catch (error) { if (!controller.signal.aborted) state.set({ pending: false, value: previous, error, ok: false }); }
      finally { if (!controller.signal.aborted && (options.poll ?? 0) > 0) timer = setTimeout(() => { void request(); }, options.poll); }
    };
    if ((options.debounce ?? 0) > 0) timer = setTimeout(() => { void request(); }, options.debounce);
    else void request();
    onCleanup(() => { controller.abort(); if (timer !== undefined) clearTimeout(timer); });
  });
  return state.asReadonly();
}
` };
}
