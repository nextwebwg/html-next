import { formatVue } from "./vue-format.js";

export const VUE_BINDINGS_PATH = "vue/bindings.ts";
export const VUE_BINDINGS_SPECIFIER = "./bindings";

export function importsVueBindings(source: string): boolean {
  return new RegExp(`from ['"]${VUE_BINDINGS_SPECIFIER}['"]`).test(source);
}

/** Application preparation/adoption over the existing binding API, emitted only for opted-in modules. */
export function vueBindingsModule(version: string): string {
  return formatVue(`// Generated by HTML Next ${version} for Vue 3.5. Do not edit.
import { getCurrentInstance, onMounted, onServerPrefetch, shallowRef } from "vue";
import { decodeHydrationValue, encodeHydrationValue } from "@nextwebwg/html-next/bindings";
import type { BindingAdoption, BindingHost, BindingPreparation, BindingScopeOptions, HydrationValue } from "@nextwebwg/html-next/bindings";
import { componentInputs } from "@nextwebwg/html-next/inputs";

const attribute = "data-html-next-bindings";
type Transfer = readonly [number, string, HydrationValue];
interface PreparedModule {
  prepare(host: BindingHost, options: Omit<BindingScopeOptions, "phase"> & { phase: "request" }): Promise<BindingPreparation>;
  adopt(host: BindingHost, adoption: BindingAdoption): void;
}

function records(value: unknown): Record<string, Transfer> {
  if (value == null || value === "") return {};
  const parsed: unknown = JSON.parse(String(value));
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) throw new TypeError("Malformed prepared module records.");
  return parsed as Record<string, Transfer>;
}

/** Restore typed producer inputs before hydration, then adopt their read identities before connection. */
export function usePreparedModule(loader: () => Promise<unknown>, options: { readonly tag: string; readonly source: string }) {
  const node = getCurrentInstance()?.vnode.el as Element | null | undefined;
  const transfer = shallowRef(records(node?.nodeType === 1 ? node.getAttribute(attribute) : undefined)[options.tag]);
  const mounted = shallowRef(false);
  let host: BindingHost | undefined;
  let adoption: BindingAdoption | undefined;
  let loading: Promise<PreparedModule> | undefined;
  const load = () => loading ??= Promise.resolve().then(loader).then(candidate => {
    const module = candidate as PreparedModule;
    if (typeof module?.prepare !== "function" || typeof module.adopt !== "function") throw new TypeError("A prepared module must export prepare and adopt functions.");
    if (adoption !== undefined) module.adopt(host!, adoption);
    return module;
  });
  onServerPrefetch(async () => {
    const module = await load();
    const controller = new AbortController();
    let prepared: BindingPreparation | undefined;
    try {
      prepared = await module.prepare(host!, { phase: "request", signal: controller.signal, source: options.source });
      const snapshot = prepared.snapshot();
      if (Object.keys(snapshot.reads).length === 0) return;
      const inputs = componentInputs(host!);
      const values = Object.fromEntries(Object.keys(snapshot.reads).filter(name => !inputs.supplied(name)).map(name =>
        [name, { value: inputs.read(name), status: inputs.status(name) }]));
      transfer.value = [1, options.source, encodeHydrationValue({ snapshot, inputs: values })];
    } finally { prepared?.dispose(); controller.abort(); }
  });
  onMounted(() => { mounted.value = true; });
  return {
    load,
    attach(target: BindingHost): void {
      host = target;
      const frame = transfer.value;
      if (frame === undefined) return;
      if (!Array.isArray(frame) || frame[0] !== 1 || frame[1] !== options.source) throw new TypeError("Prepared module source revision does not match.");
      const value = decodeHydrationValue(frame[2]) as BindingAdoption;
      if (value === null || typeof value !== "object" || value.snapshot?.source !== options.source || typeof value.inputs !== "object" || value.inputs === null) throw new TypeError("Malformed prepared module transfer.");
      const inputs = componentInputs(target);
      for (const [name, snapshot] of Object.entries(value.inputs)) {
        if (inputs.supplied(name)) continue;
        const source = inputs.source(name);
        try { if (!source.publish(snapshot)) throw new TypeError("Prepared module output failed its declared type."); }
        finally { source.dispose(); }
      }
      adoption = value;
    },
    attributes(attrs: Record<string, unknown>): Record<string, unknown> {
      const inherited = records(attrs[attribute]);
      const result = { ...inherited };
      if (mounted.value || transfer.value === undefined) delete result[options.tag];
      else result[options.tag] = transfer.value;
      const names = Object.keys(result).sort();
      return { ...attrs, [attribute]: names.length === 0 ? undefined : JSON.stringify(Object.fromEntries(names.map(name => [name, result[name]]))) };
    },
  };
}
`, "bindings.ts");
}
