import type { GeneratedArtifact } from "../generate.js";

/** Prepare through Angular stability, and restore typed inputs before the first template check. */
export function angularBindingsArtifact(version: string): GeneratedArtifact {
  return { path: "angular/bindings.ts", content: `// Generated by HTML Next ${version}. Do not edit.
import { ApplicationRef, DestroyRef, PLATFORM_ID, PendingTasks, inject } from "@angular/core";
import { componentInputs } from "@nextwebwg/html-next/inputs";
import { decodeHydrationValue, encodeHydrationValue, type BindingAdoption, type BindingHost, type BindingPreparation, type BindingScopeOptions } from "@nextwebwg/html-next/bindings";
export interface PreparedModule {
  prepare(host: BindingHost, options: Omit<BindingScopeOptions, "phase"> & { phase: "request" }): Promise<BindingPreparation>;
  adopt(host: BindingHost, adoption: BindingAdoption): void;
}
const attribute = "data-html-next-bindings";
export function preparedModule(loader: () => Promise<unknown>, options: { tag: string; source: string }) {
  const browser = inject(PLATFORM_ID) === "browser", tasks = inject(PendingTasks), application = inject(ApplicationRef);
  const controller = new AbortController(), destroy = inject(DestroyRef);
  destroy.onDestroy(() => controller.abort());
  let host: BindingHost & { root: Element }, adoption: BindingAdoption | undefined, loading: Promise<PreparedModule> | undefined;
  const records = () => JSON.parse(host.root.getAttribute(attribute) ?? "{}") as Record<string, any>;
  const load = () => loading ??= Promise.resolve().then(loader).then(candidate => {
    const module = candidate as PreparedModule;
    if (typeof module?.prepare !== "function" || typeof module.adopt !== "function") throw new TypeError("A prepared module must export prepare and adopt functions.");
    if (adoption) module.adopt(host, adoption);
    return module;
  });
  return { load, attach(target: typeof host): void {
    host = target;
    if (browser) {
      const all = records(), frame = all[options.tag];
      if (frame === undefined) return;
      if (!Array.isArray(frame) || frame[0] !== 1 || frame[1] !== options.source) throw new TypeError("Prepared module source revision does not match.");
      const value = decodeHydrationValue(frame[2]) as BindingAdoption;
      if (value?.snapshot?.source !== options.source || typeof value.inputs !== "object" || value.inputs === null) throw new TypeError("Malformed prepared module transfer.");
      const inputs = componentInputs(host);
      for (const [name, snapshot] of Object.entries(value.inputs)) {
        if (inputs.supplied(name)) continue;
        const source = inputs.source(name);
        try { if (!source.publish(snapshot)) throw new TypeError("Prepared module output failed its declared type."); } finally { source.dispose(); }
      }
      adoption = value; delete all[options.tag];
      if (Object.keys(all).length) host.root.setAttribute(attribute, JSON.stringify(all)); else host.root.removeAttribute(attribute);
      return;
    }
    const inputs = componentInputs(host);
    const read = (name: string) => {
      let value: unknown; try { value = encodeHydrationValue(inputs.read(name)); } catch { value = null; }
      return [name, value, inputs.status(name), inputs.names.includes(name) && inputs.supplied(name)];
    };
    const selected = (names: readonly string[]) => inputs.readNames.filter(name => !names.includes(name) || inputs.names.includes(name) && inputs.supplied(name));
    const signature = (names: readonly string[]) => JSON.stringify(selected(names).map(read));
    let prepared: BindingPreparation | undefined, stop = () => {}, generation = 0;
    destroy.onDestroy(() => { generation++; stop(); prepared?.dispose(); });
    void tasks.run(async () => {
      const module = await load();
      const initial = new Map(inputs.readNames.map(name => [name, read(name)]));
      const first = module.prepare(host, { phase: "request", signal: controller.signal, source: options.source });
      application.tick();
      prepared = await first;
      if (controller.signal.aborted) { prepared.dispose(); return; }
      const names = prepared.names;
      // Parent producers may complete after a child. Keep its transfer tied to its final inputs.
      let previous = JSON.stringify(selected(names).map(name => initial.get(name)));
      const write = () => {
        const snapshot = prepared!.snapshot(), all = records();
        delete all[options.tag];
        if (Object.keys(snapshot.reads).length) {
          const values = Object.fromEntries(Object.keys(snapshot.reads).filter(name => !inputs.supplied(name)).map(name => [name, { value: inputs.read(name), status: inputs.status(name) }]));
          all[options.tag] = [1, options.source, encodeHydrationValue({ snapshot, inputs: values })];
        }
        if (Object.keys(all).length) host.root.setAttribute(attribute, JSON.stringify(all)); else host.root.removeAttribute(attribute);
      };
      write();
      stop = inputs.watch(() => {
        const next = signature(names);
        if (next === previous) return;
        previous = next;
        const current = ++generation;
        prepared?.dispose();
        void tasks.run(async () => {
          await Promise.resolve();
          if (controller.signal.aborted || current !== generation) return;
          const pending = module.prepare(host, { phase: "request", signal: controller.signal, source: options.source });
          application.tick();
          const result = await pending;
          if (controller.signal.aborted || current !== generation) { result.dispose(); return; }
          prepared = result; write();
        });
      });
    });
  } };
}
` };
}
