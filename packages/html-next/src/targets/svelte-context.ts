/**
 * The component a `<slot of>` outlet renders a child's slot content in: it gives that content the
 * child's contexts, so a `<context>` in it reads the child, then the parent (components#slot-of).
 * Svelte sets context only while a component initializes, so this is a component, not a helper.
 * When it goes, or holds another child's content, it lets plain content it held go (`release`).
 */
import type { GeneratedArtifact } from "../generate.js";

export const SVELTE_CONTEXT_PATH = "svelte/context.svelte";
export const SVELTE_CONTEXT_SPECIFIER = "./context.svelte";

export function svelteContextArtifact(version: string): GeneratedArtifact {
  return Object.freeze({ path: SVELTE_CONTEXT_PATH, content: `<!-- Generated by HTML Next ${version} for Svelte 5. Do not edit. -->
<script lang="ts">
	import { setContext, untrack, type Snippet } from "svelte";
	let { contexts, release, children }: { contexts?: Map<unknown, unknown> | undefined; release?: (() => void) | undefined; children: Snippet } = $props();
	untrack(() => { for (const [key, value] of contexts ?? []) setContext(key, value); });
	// A derived value changes only when the release does, so a re-read of the same hold keeps it.
	const held = $derived(release);
	$effect(() => held);
</script>

{@render children()}
` });
}
