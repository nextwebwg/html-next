import { CLASS_BINDINGS_SOURCE } from "./class-text.js";
import { DOM_ATTRIBUTES_SOURCE } from "../generated/dom-attributes-source.js";
import type { GeneratedArtifact } from "../generate.js";

export function attributeHelperArtifact(target: "react" | "vue" | "svelte" | "angular", version: string): GeneratedArtifact {
  return { path: `${target}/attributes.ts`, content: `// Generated by HTML Next ${version}. Do not edit.\n${target === "angular" ? 'import { Directive, ElementRef, Input, inject } from "@angular/core";\n' : ""}${DOM_ATTRIBUTES_SOURCE}\n${CLASS_BINDINGS_SOURCE}${target !== "angular" ? "" : `
@Directive({ selector: "[hnNextNamespaces]", standalone: true })
export class HtmlNextNamespacedAttributes {
  private readonly element = inject<ElementRef<Element>>(ElementRef).nativeElement;
  private previous: readonly NamespacedAttribute[] | undefined;
  @Input() set hnNextNamespaces(value: readonly NamespacedAttribute[]) {
    applyNamespacedAttributes(this.element, value, this.previous);
    this.previous = value;
  }
}

@Directive({ selector: "[hnNextClasses]", standalone: true })
export class HtmlNextClasses {
  private readonly element = inject<ElementRef<Element>>(ElementRef).nativeElement;
  private previous: unknown[] | undefined;
  @Input() set hnNextClasses(value: ClassBindingInput) {
    this.previous ??= initializeClassBindings(this.element, value);
    applyClassBindings(this.element, value, this.previous);
  }
}
`}` };
}
