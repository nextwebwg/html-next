import type { GeneratedArtifact } from "../generate.js";

export function angularValidityArtifact(version: string): GeneratedArtifact {
  return { path: "angular/validity.ts", content: `// Generated by HTML Next ${version}. Do not edit.
import { Directive, ElementRef, PLATFORM_ID, inject } from "@angular/core";
import { mountPropValidity, updatePropValidity } from "./state";
export type ValidityBinding = Parameters<typeof mountPropValidity>[1];
@Directive({ selector: "[hnNextValidity]", standalone: true })
export class HtmlNextValidity {
  read: () => readonly ValidityBinding[] = () => [];
  private readonly element = inject<ElementRef<Element>>(ElementRef).nativeElement;
  private readonly browser = inject(PLATFORM_ID) === "browser";
  private stop: (() => void) | undefined;
  ngAfterViewChecked(): void {
    if (!this.browser) return;
    const models = [...this.read()].reverse();
    const binding: ValidityBinding = { contract: { props: Object.fromEntries(models.flatMap(model => Object.entries(model.contract.props))) }, values: Object.fromEntries(models.flatMap(model => Object.entries(model.values))) };
    if (this.stop) updatePropValidity(this.element, binding);
    else this.stop = mountPropValidity(this.element, binding);
  }
  ngOnDestroy(): void { this.stop?.(); }
}
` };
}
