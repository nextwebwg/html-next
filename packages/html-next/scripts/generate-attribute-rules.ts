import { mkdir, readFile, writeFile } from "node:fs/promises";
import { URL_ATTRIBUTES } from "../src/sanitize.js";
import { ENUMERATED_BOOLEAN_ATTRIBUTE_NAMES, ENUMERATED_BOOLEAN_ATTRIBUTE_PREFIX } from "../src/expression.js";

const alternatives = (names: readonly string[]): string => names.map(name => JSON.stringify(name)).join(" or ");
const expressionFile = new URL("../src/expression.ts", import.meta.url);
const expression = await readFile(expressionFile, "utf8");
const enumeratedFunction = /export function isEnumeratedBoolean\(name: string\): boolean \{[\s\S]*?\n\}/;
if (!enumeratedFunction.test(expression)) throw new Error("Cannot find the enumerated attribute predicate in expression.ts.");
const predicate = `export function isEnumeratedBoolean(name: string): boolean {\n  return name.startsWith(${JSON.stringify(ENUMERATED_BOOLEAN_ATTRIBUTE_PREFIX)})${ENUMERATED_BOOLEAN_ATTRIBUTE_NAMES.map(name => ` || name === ${JSON.stringify(name)}`).join("")};\n}`;
const outputs = new Map([
  [new URL("../../html-next-dotnet/src/HtmlNext/Generated/AttributeRules.g.cs", import.meta.url),
    `// Generated by html-next/scripts/generate-attribute-rules.ts.\nnamespace HtmlNext;\n\ninternal static class BoundAttributeRules\n{\n    public static bool IsUrl(string name) => name is ${alternatives([...URL_ATTRIBUTES])};\n    public static bool IsEnumeratedBoolean(string name) => name.StartsWith(${JSON.stringify(ENUMERATED_BOOLEAN_ATTRIBUTE_PREFIX)}, StringComparison.Ordinal)\n        || name is ${alternatives(ENUMERATED_BOOLEAN_ATTRIBUTE_NAMES)};\n}\n`],
  [expressionFile, expression.replace(enumeratedFunction, predicate)],
]);
for (const [output, content] of outputs) {
  if (process.argv.includes("--check")) {
    if (await readFile(output, "utf8").catch(() => "") !== content) throw new Error(`${output.pathname} is stale; run pnpm exec tsx scripts/generate-attribute-rules.ts in packages/html-next.`);
  } else {
    await mkdir(new URL("./", output), { recursive: true });
    await writeFile(output, content);
  }
}
